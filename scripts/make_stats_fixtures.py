"""Generate tests/fixtures/stats_expected.json for the TypeScript stats tests.

Run from the repo root:  python scripts/make_stats_fixtures.py

Every "expected" number comes from pipeline/trend.py (Mann-Kendall, Sen,
OLS slope, lag-1) or directly from scipy (OLS stderr/t/CI, which trend.py does
not expose). Input series are fixed or generated from a seeded RNG, rounded to
3 decimals so the JSON round-trips exactly. Nothing here is real NASA data; it
is synthetic input for checking the arithmetic.
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import numpy as np
from scipy import stats

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from pipeline.trend import mann_kendall_sen  # noqa: E402

OUT = ROOT / "tests" / "fixtures" / "stats_expected.json"


def clean(value):
    if isinstance(value, dict):
        return {k: clean(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [clean(v) for v in value]
    if isinstance(value, (np.floating, float)):
        value = float(value)
        return None if math.isnan(value) or math.isinf(value) else value
    if isinstance(value, np.integer):
        return int(value)
    if isinstance(value, np.bool_):
        return bool(value)
    return value


def r3(a):
    return [round(float(v), 3) for v in a]


def build_cases():
    rng = np.random.default_rng(20261115)
    years45 = list(range(1981, 2026))
    t = np.arange(45)
    cases = []

    cases.append(("positive_trend_noise", years45, r3(0.05 * t + rng.normal(0, 0.4, 45)), None))
    cases.append(("negative_trend_noise", years45, r3(-3.0 * t + rng.normal(0, 40, 45) + 900), None))
    cases.append(("no_trend_noise", years45, r3(rng.normal(25, 1.5, 45)), None))

    ties = [int(v) for v in rng.integers(0, 6, 30)]
    cases.append(("many_ties_integers", list(range(1996, 2026)), ties, None))

    vals = r3(0.8 * np.arange(25) + rng.normal(0, 2.0, 25) + 100)
    vals_missing = list(vals)
    for i in (3, 4, 11, 20):
        vals_missing[i] = None
    cases.append(("missing_values_listed_as_null", list(range(2001, 2026)), vals_missing, None))

    gap_years = [y for y in range(1981, 2026) if y not in (1990, 1991, 2005)]
    gv = r3(0.02 * np.array(gap_years) + rng.normal(0, 0.3, len(gap_years)))
    cases.append(("year_gaps_lag1_pairs_only", gap_years, gv, None))

    e = rng.normal(0, 1, 45)
    ar = np.zeros(45)
    for i in range(1, 45):
        ar[i] = 0.7 * ar[i - 1] + e[i]
    cases.append(("ar1_noise_phi_0.7", years45, r3(ar + 0.03 * t), None))

    cases.append(("three_points_minimum", [2001, 2002, 2003], [1.0, 2.5, 2.0], None))
    cases.append(("constant_series", list(range(2001, 2011)), [5.0] * 10, None))
    cases.append(("perfect_line", list(range(2001, 2011)), [10.0 + 2.0 * i for i in range(10)], None))
    cases.append(("too_few_points_error", [2001, 2002], [1.0, 2.0], "error"))
    return cases


def main():
    out = {
        "note": "Generated by scripts/make_stats_fixtures.py from pipeline/trend.py + scipy. Synthetic inputs.",
        "scipy_version": __import__("scipy").__version__,
        "tolerance": 1e-6,
        "cases": [],
    }
    for name, years, values, mode in build_cases():
        case = {"name": name, "years": years, "values": values, "alpha": 0.05}
        if mode == "error":
            try:
                mann_kendall_sen(years, values)
            except ValueError as exc:
                case["expect_error"] = str(exc)
            else:
                raise SystemExit(f"{name}: expected ValueError")
        else:
            res = mann_kendall_sen(years, values)
            pairs = [(y, v) for y, v in zip(years, values) if v is not None]
            x = np.array([p[0] for p in pairs], float)
            yv = np.array([p[1] for p in pairs], float)
            lr = stats.linregress(x, yv)
            df = len(x) - 2
            tc = float(stats.t.ppf(0.975, df))
            res["ols_intercept"] = float(lr.intercept)
            res["ols_stderr"] = float(lr.stderr)
            res["ols_t"] = float(lr.slope / lr.stderr) if lr.stderr > 0 else None
            res["ols_slope_ci95"] = [float(lr.slope - tc * lr.stderr), float(lr.slope + tc * lr.stderr)]
            if not np.isfinite(lr.stderr) or lr.stderr == 0:
                # Zero residual variance (constant or perfectly linear data): scipy returns
                # NaN/inf for the OLS inference fields, so they are not compared. The TS code
                # reports a finite, documented value instead. MK, Sen, slope and lag-1 are still checked.
                for key in ("ols_p_value", "ols_stderr", "ols_t", "ols_slope_ci95"):
                    res.pop(key, None)
                case["ols_inference_skipped"] = "zero residual variance"
            case["expected"] = clean(res)
        out["cases"].append(case)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(out, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUT} with {len(out['cases'])} cases")


if __name__ == "__main__":
    main()
